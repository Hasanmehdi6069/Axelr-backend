def stem_word(word: str) -> str:
    word = word.lower().strip()
    for suffix in _STEM_SUFFIXES_SORTED:
        if len(word) - len(suffix) >= 3 and word.endswith(suffix):
            return word[: -len(suffix)]
    return word


def normalize_word(text: str) -> str:
    return re.sub(r"[^a-zA-Z0-9]+", " ", text.lower()).strip()


def extract_negated_terms(text: str) -> Set[str]:
    """
    Tokens within a negation window + prefix-negated stems.

    v19.2: prefix negation restored (test contract). Fixed to only strip
    when len(word) > len(prefix)+2 — avoids 'under'->'der' regression.
    Contractions ('don't', 'won't', …) are normalized first.
    """
    low = text.lower()
    for contr, repl in _CONTRACTION_MAP.items():
        if contr in low:
            low = low.replace(contr, repl)
    words = re.findall(r"[a-z][a-z0-9_]*", low)
    negated: Set[str] = set()
    window = 0
    for w in words:
        if w in _NEGATION_TERMS:
            window = _NEGATION_WINDOW
            continue
        if window > 0:
            negated.add(w)
            window -= 1
            continue
        for prefix in _NEGATION_PREFIXES:
            if w.startswith(prefix) and len(w) > len(prefix) + 2:
                negated.add(w[len(prefix) :])
                break
    return negated


def _quadgrams_of(w: str) -> Tuple[str, ...]:
    t = f"^{w}$"
    if len(t) < 4:
        return ()
    return tuple(t[i : i + 4] for i in range(len(t) - 3))


def _fnv32(s: str) -> int:
    h = 0x811C9DC5
    for c in s.encode("utf-8"):
        h = ((h ^ c) * 0x01000193) & 0xFFFFFFFF
    return h


